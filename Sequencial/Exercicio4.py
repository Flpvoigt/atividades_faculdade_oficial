primeiro_valor = float(input("Digite o primeiro número: "))
segundo_valor = float(input("Digite o segundo número: "))

Soma = primeiro_valor + segundo_valor
Subtração = primeiro_valor - segundo_valor
Multiplicação = primeiro_valor * segundo_valor
Potenciação = primeiro_valor ** segundo_valor
Divisão = primeiro_valor / segundo_valor
Parteinteira =  primeiro_valor // segundo_valor
Resto = primeiro_valor % segundo_valor
Raiz = primeiro_valor ** (1 / segundo_valor)

print(f"soma: {Soma}\nSubtracao: {Subtração}\nMultiplicação: {Multiplicação:.2f}\nPotenciação: {Potenciação:.2f}\nDivisão: {Divisão:.2f}\nParteinteira: {Parteinteira:.2f}\nResto: {Resto:.2f}\nRaiz: {Raiz:.2f}")
